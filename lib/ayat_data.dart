  static Map<String, String> getAyatHariIni(DateTime localDate) {
    final day = DateTime.utc(
      localDate.year,
      localDate.month,
      localDate.day,
    ).difference(DateTime.utc(2026, 1, 1)).inDays;
    return daftarAyat[day % daftarAyat.length];
  }

  // Pertahankan nama API untuk pemanggil lama.
  static Map<String, String> getAyatAcak() => getAyatHariIni(DateTime.now());
